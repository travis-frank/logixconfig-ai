"""Read equipment lists from CSV, and write tags and draft documentation."""

import csv
from pathlib import Path

from pydantic import ValidationError

from logixconfig.models import Equipment, EquipmentType, Tag

REQUIRED_COLUMNS = ("name", "type", "description")
TAG_CSV_COLUMNS = ("name", "data_type", "description", "equipment")

SUGGESTED_ALARMS: dict[EquipmentType, tuple[tuple[str, str], ...]] = {
    EquipmentType.PUMP: (
        ("Fault", "{name}_Fault is on"),
        ("Fail to start", "{name}_Run_Cmd is on and {name}_Run_Fb is still off after a start delay"),
    ),
    EquipmentType.VALVE: (
        ("Fail to open", "{name}_Open_Cmd is on and {name}_Open_Fb is still off after the travel time"),
        ("Fail to close", "{name}_Open_Cmd is off and {name}_Closed_Fb is still off after the travel time"),
        ("Position fault", "{name}_Open_Fb and {name}_Closed_Fb are both on"),
    ),
    EquipmentType.LEVEL_TRANSMITTER: (
        ("High level", "{name}_PV is above {name}_Hi_SP (sets {name}_Hi_Alm)"),
        ("Low level", "{name}_PV is below {name}_Lo_SP (sets {name}_Lo_Alm)"),
    ),
    EquipmentType.PRESSURE_TRANSMITTER: (
        ("High pressure", "{name}_PV is above {name}_Hi_SP (sets {name}_Hi_Alm)"),
        ("Low pressure", "{name}_PV is below {name}_Lo_SP (sets {name}_Lo_Alm)"),
    ),
}


def read_equipment(csv_path: str | Path) -> list[Equipment]:
    with open(csv_path, newline="", encoding="utf-8-sig") as file:
        reader = csv.DictReader(file)
        if reader.fieldnames is None:
            return []
        _check_columns(reader.fieldnames)
        return [
            _row_to_equipment(row, line_number=reader.line_num)
            for row in reader
            if not _is_blank(row)
        ]


def _check_columns(fieldnames: list[str]) -> None:
    present = {name.strip().lower() for name in fieldnames}
    missing = [column for column in REQUIRED_COLUMNS if column not in present]
    if missing:
        raise ValueError(f"CSV is missing required columns: {', '.join(missing)}")


def _row_to_equipment(row: dict[str, str], line_number: int) -> Equipment:
    values = {key.strip().lower(): (value or "").strip() for key, value in row.items() if key}
    equipment_type = _parse_type(values["type"], line_number)
    try:
        return Equipment(name=values["name"], type=equipment_type, description=values["description"])
    except ValidationError as error:
        raise ValueError(f"Line {line_number}: invalid equipment ({_summarize(error)})") from None


def _summarize(error: ValidationError) -> str:
    return "; ".join(
        f"{'.'.join(str(part) for part in detail['loc'])}: {detail['msg']}" for detail in error.errors()
    )


def _parse_type(raw: str, line_number: int) -> EquipmentType:
    try:
        return EquipmentType(raw.lower())
    except ValueError:
        valid = ", ".join(t.value for t in EquipmentType)
        raise ValueError(f"Line {line_number}: unknown equipment type '{raw}' (expected one of: {valid})") from None


def _is_blank(row: dict[str, str]) -> bool:
    return all(not (value or "").strip() for key, value in row.items() if key)


def write_tags_csv(tags: list[Tag], path: str | Path) -> None:
    with open(path, "w", newline="", encoding="utf-8") as file:
        writer = csv.writer(file)
        writer.writerow(TAG_CSV_COLUMNS)
        for tag in tags:
            writer.writerow([tag.name, tag.data_type.value, tag.description, tag.equipment])


NARRATIVE_HEADING = "## Control narrative"


def write_docs(equipment: list[Equipment], tags: list[Tag], path: str | Path, narrative: str | None = None) -> None:
    Path(path).write_text(render_docs(equipment, tags, narrative), encoding="utf-8")


def render_docs(equipment: list[Equipment], tags: list[Tag], narrative: str | None = None) -> str:
    sections = [
        "# Draft Tag Documentation",
        "Generated by logixconfig. This is a draft for engineering review.",
        "## Equipment",
        _markdown_table(("Name", "Type", "Description"), [(e.name, e.type.value, e.description) for e in equipment]),
        "## Tags",
        _markdown_table(
            ("Tag", "Data type", "Description", "Equipment"),
            [(t.name, t.data_type.value, t.description, t.equipment) for t in tags],
        ),
        "## Suggested Alarms",
        "Delays, travel times, and setpoint values must be set by the engineer.",
        _markdown_table(("Equipment", "Alarm", "Condition"), suggested_alarm_rows(equipment)),
    ]
    if narrative:
        sections += [NARRATIVE_HEADING, narrative.strip()]
    return "\n\n".join(sections) + "\n"


def suggested_alarm_rows(equipment: list[Equipment]) -> list[tuple[str, str, str]]:
    return [
        (item.name, alarm, condition.format(name=item.name))
        for item in equipment
        for alarm, condition in SUGGESTED_ALARMS[item.type]
    ]


def _markdown_table(headers: tuple[str, ...], rows: list[tuple[str, ...]]) -> str:
    lines = [_markdown_row(headers), _markdown_row(tuple("---" for _ in headers))]
    lines.extend(_markdown_row(row) for row in rows)
    return "\n".join(lines)


def _markdown_row(cells: tuple[str, ...]) -> str:
    escaped = (cell.replace("|", "\\|") for cell in cells)
    return "| " + " | ".join(escaped) + " |"
